def run_skill():
    target = get_observation()["task_target"]
    if target != PROFILE["target"]:
        raise ValueError("Skill target does not match task: " + target)
    home = get_robot_state()
    stage("PREPARE_OPEN", open_gripper)
    park = np.asarray(home["position"]).copy(); park[1] += .25
    stage("CLEAR_VIEW", goto_pose, park, home["quaternion_wxyz"], duration_s=1.5)
    grasp, points = stage("PERCEIVE", observe_target)
    slot = get_tray_slot()
    plan = stage("GRASP_POSE", prepare_grasp, grasp, points, slot, home)
    plan = execute_pick(plan)
    plan = execute_transfer(plan, slot)
    execute_place(plan, slot, home)
    # The worker's independent evaluator decides physical success, not this log.
    print("Full-stage program completed; inspect result.json for physical success")


run_skill()
